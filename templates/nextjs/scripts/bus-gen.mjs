#!/usr/bin/env node
// Generates src/bus/messages.ts and src/bus/dispatch.ts from src/bus/domains/<domain>/.
//
// Each domain folder has:
//   messages.ts  export type <Name>Command = { type: '<domain>/<action>'; ... } | ...
//                export type <Name>Event   = { type: '<domain>/<happened>'; ... } | ...
//   handlers.ts  export async function handle<Action>(cmd, ctx) { ... }   (one per command)
//
// The dispatcher is a switch that calls named, imported handlers, so static tools
// (Graphify, the TypeScript compiler) see every edge. Run after adding a message:
//   node scripts/bus-gen.mjs                 write the files
//   node scripts/bus-gen.mjs --check         exit 1 if the generated files are out of date (CI)
//   node scripts/bus-gen.mjs --dir lib/bus   bus folder when it is not src/bus
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dirFlag = process.argv.indexOf('--dir');
const busDir = dirFlag > 0 ? process.argv[dirFlag + 1] : 'src/bus';
const domainsDir = join(busDir, 'domains');
const header = '// GENERATED by scripts/bus-gen.mjs. Do not edit; change src/bus/domains/<domain>/ instead.\n';

const pascal = (s) => s.replace(/(^|[-_])(\w)/g, (_, __, c) => c.toUpperCase());

function unionBlock(text, typeName) {
  const start = text.search(new RegExp(`export\\s+type\\s+${typeName}\\s*=`));
  if (start < 0) return '';
  const rest = text.slice(start + 1);
  const next = rest.search(/\n\s*export\s/);
  return next < 0 ? text.slice(start) : text.slice(start, start + 1 + next);
}

function readDomain(domain) {
  const dir = join(domainsDir, domain);
  const messagesPath = join(dir, 'messages.ts');
  if (!existsSync(messagesPath)) return null;
  const text = readFileSync(messagesPath, 'utf8');
  const commandType = text.match(/export\s+type\s+(\w+Command)\s*=/)?.[1];
  const eventType = text.match(/export\s+type\s+(\w+Event)\s*=/)?.[1];
  const literals = (block) => [...block.matchAll(/type\s*:\s*['"]([\w-]+\/[\w-]+)['"]/g)].map((m) => m[1]);
  const commands = commandType ? literals(unionBlock(text, commandType)) : [];
  const events = eventType ? literals(unionBlock(text, eventType)) : [];
  const handlersPath = join(dir, 'handlers.ts');
  const handlersText = existsSync(handlersPath) ? readFileSync(handlersPath, 'utf8') : '';
  const problems = [];
  const handlers = commands.map((type) => {
    const [prefix, action] = type.split('/');
    if (prefix !== domain) problems.push(`${type}: prefix should be '${domain}/'`);
    const name = `handle${pascal(action)}`;
    const exported = new RegExp(`export\\s+(async\\s+)?function\\s+${name}\\b|export\\s+const\\s+${name}\\b`);
    if (!exported.test(handlersText)) problems.push(`${type}: export ${name} from ${handlersPath}`);
    return { type, name };
  });
  for (const type of events) {
    if (type.split('/')[0] !== domain) problems.push(`${type}: prefix should be '${domain}/'`);
  }
  return { domain, commandType, eventType, handlers, events, problems };
}

function generate() {
  const domains = existsSync(domainsDir)
    ? readdirSync(domainsDir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()
    : [];
  const parsed = domains.map(readDomain).filter(Boolean);
  const problems = parsed.flatMap((d) => d.problems);
  const seen = new Map();
  for (const d of parsed) {
    for (const t of [...d.handlers.map((h) => h.type), ...d.events]) {
      if (seen.has(t)) problems.push(`${t}: declared in ${seen.get(t)} and ${d.domain}`);
      seen.set(t, d.domain);
    }
  }
  const typeImports = parsed
    .filter((d) => d.commandType || d.eventType)
    .map((d) => `import type { ${[d.commandType, d.eventType].filter(Boolean).join(', ')} } from './domains/${d.domain}/messages';`);
  const commands = parsed.map((d) => d.commandType).filter(Boolean);
  const events = parsed.map((d) => d.eventType).filter(Boolean);
  const messages = [
    header,
    ...typeImports,
    typeImports.length ? '' : null,
    `export type Command = ${commands.join(' | ') || 'never'};`,
    `export type BusEvent = ${events.join(' | ') || 'never'};`,
    '',
  ].filter((l) => l !== null).join('\n');

  const handlerImports = parsed
    .filter((d) => d.handlers.length)
    .map((d) => `import { ${d.handlers.map((h) => h.name).join(', ')} } from './domains/${d.domain}/handlers';`);
  const cases = parsed.flatMap((d) => d.handlers.map((h) => `    case '${h.type}':\n      return ${h.name}(cmd, ctx);`));
  const dispatch = [
    header,
    "import type { BusContext } from './context';",
    "import type { Command } from './messages';",
    ...handlerImports,
    '',
    'export async function dispatch(cmd: Command, ctx: BusContext): Promise<void> {',
    '  ctx.log(cmd);',
    '  switch (cmd.type) {',
    ...cases,
    '    default: {',
    '      const unhandled: never = cmd;',
    '      throw new Error(`unhandled command ${JSON.stringify(unhandled)}`);',
    '    }',
    '  }',
    '}',
    '',
  ].join('\n');
  return { messages, dispatch, problems, count: seen.size };
}

const { messages, dispatch, problems, count } = generate();
if (problems.length) {
  console.error('bus-gen: fix these first:\n  ' + problems.join('\n  '));
  process.exit(1);
}
const targets = [[join(busDir, 'messages.ts'), messages], [join(busDir, 'dispatch.ts'), dispatch]];
if (process.argv.includes('--check')) {
  const stale = targets.filter(([path, content]) => !existsSync(path) || readFileSync(path, 'utf8') !== content);
  if (stale.length) {
    console.error(`bus-gen: out of date: ${stale.map(([p]) => p).join(', ')}. Run node scripts/bus-gen.mjs`);
    process.exit(1);
  }
  console.log(`bus-gen: up to date (${count} message types)`);
} else {
  for (const [path, content] of targets) writeFileSync(path, content);
  console.log(`bus-gen: wrote ${targets.map(([p]) => p).join(', ')} (${count} message types)`);
}
